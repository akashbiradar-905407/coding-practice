// increment vs decrement operators


#include <iostream>
  using namespace std;

  int main (){

     int x = 5;

     cout<<x<<endl;

     // 1st 'x' value then increment x+1 or x-1;

     x++;
     cout<<x<<endl;          

     x--;
     cout<<x<<endl;


     // 1st increment x+1 or x-1 then 'x' value ;

     ++x;
     cout<<x<<endl;

     --x;
     cout<<x<<endl;

     

return 0;



  }